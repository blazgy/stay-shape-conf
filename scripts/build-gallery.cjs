// Rebuild web images and static gallery markup from the supplied FES photographs.
// Usage: node scripts/build-gallery.cjs /path/to/originals
const fs = require('node:fs/promises');
const path = require('node:path');
const { createCanvas, loadImage } = require('@napi-rs/canvas');
const root = path.resolve(__dirname, '..');
const source = require('../data/gallery-source.json');
const escape = value => String(value).replace(/[&<>"']/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
const tr = values => ['en', 'de', 'bhs'].map((lang, i) => `data-${lang}="${escape(values[i])}"`).join(' ');

async function main() {
  const input = process.argv[2];
  if (!input) throw new Error('Pass the directory containing the original FES JPGs.');
  const output = path.join(root, 'assets/conference');
  await fs.mkdir(output, { recursive: true });
  const photos = [];
  for (const [number, category, captionKey] of source.photos) {
    const id = `FES-${number}`;
    const image = await loadImage(path.join(input, `${id}.jpg`));
    const variants = [];
    for (const target of [400, 800, image.width]) {
      const width = Math.min(target, image.width);
      if (variants.some(v => v.width === width)) continue;
      const height = Math.round(image.height * width / image.width);
      const canvas = createCanvas(width, height);
      canvas.getContext('2d').drawImage(image, 0, 0, width, height);
      const filename = `${id}-${width}.webp`;
      await fs.writeFile(path.join(output, filename), await canvas.encode('webp', 82));
      variants.push({ width, src: `./assets/conference/${filename}` });
    }
    const captions = source.captions[captionKey];
    photos.push({ id, category, caption: Object.fromEntries(['en', 'de', 'bhs'].map((lang, i) => [lang, captions[i]])), width: image.width, height: image.height, variants });
  }
  function tile(photo, featured = false, index = 0) {
    const captions = Object.values(photo.caption);
    const full = photo.variants.at(-1).src;
    const sizes = featured ? (index === 0 ? '(max-width: 720px) 90vw, 45vw' : '(max-width: 720px) 45vw, 25vw') : '(max-width: 520px) 90vw, (max-width: 900px) 44vw, 28vw';
    const crops = { 'FES-85': '50% 56%', 'FES-122': '50% 48%', 'FES-147': '50% 52%', 'FES-69': '60% 48%' };
    return `<a class="photo-tile${featured ? ` bento-tile bento-tile-${index + 1}` : ''}" href="${full}" data-photo-id="${photo.id}" data-category="${photo.category}"${featured ? ` style="--photo-position:${crops[photo.id] || 'center'}"` : ''}>
      <img src="${photo.variants.find(v => v.width === 800)?.src || full}" srcset="${photo.variants.map(v => `${v.src} ${v.width}w`).join(', ')}" sizes="${sizes}" width="${photo.width}" height="${photo.height}" alt="${escape(captions[0])}" data-photo-alt="${photo.id}" loading="lazy" decoding="async">
      <span class="photo-open" aria-hidden="true">↗</span>
      <span class="photo-tile-caption" ${tr(captions)}>${escape(captions[0])}</span>
    </a>`;
  }
  await fs.writeFile(path.join(root, 'gallery-data.js'), `// Generated by scripts/build-gallery.cjs. Photography © FES.\nwindow.conferencePhotos = ${JSON.stringify(photos)};\n`);
  for (const [file, marker, content] of [
    ['index.html', 'GALLERY-BENTO', source.featured.map((n, i) => tile(photos.find(p => p.id === `FES-${n}`), true, i)).join('\n')],
    ['gallery.html', 'GALLERY-PHOTOS', photos.map(p => tile(p)).join('\n')],
  ]) {
    const filename = path.join(root, file);
    let html = await fs.readFile(filename, 'utf8');
    const pattern = new RegExp(`(<!-- ${marker}:START -->)[\\s\\S]*?(<!-- ${marker}:END -->)`);
    if (!pattern.test(html)) throw new Error(`Missing ${marker} markers in ${file}`);
    html = html.replace(pattern, `$1\n${content}\n$2`);
    await fs.writeFile(filename, html);
  }
  console.log(`Prepared ${photos.length} photographs and ${source.featured.length} homepage tiles. Originals unchanged.`);
}
main().catch(error => { console.error(error); process.exitCode = 1; });
